CREATE TABLE S2C_USER_ROLE
(
    USER_ROLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,

    VALID_FROM DATE DEFAULT SYSDATE NOT NULL,
    VALID_TO DATE,

    REASON VARCHAR2(500),

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_USER_ROLE PRIMARY KEY (USER_ROLE_ID),
    CONSTRAINT FK_S2C_UR_USER FOREIGN KEY (USER_ID) REFERENCES S2C_USER(USER_ID),
    CONSTRAINT FK_S2C_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES S2C_ROLE(ROLE_ID),
    -- 유효기간과 활성 중복 방지
    CONSTRAINT CK_S2C_UR_PERIOD CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CK_S2C_UR_USE CHECK (USE_YN IN ('Y', 'N'))
);

-- 종료일이 없는 활성 사용자-역할 중복 행을 차단한다.
CREATE UNIQUE INDEX UX_S2C_UR_OPEN_ACTIVE
    ON S2C_USER_ROLE (
                      CASE WHEN USE_YN = 'Y' AND VALID_TO IS NULL THEN USER_ID END,
                      CASE WHEN USE_YN = 'Y' AND VALID_TO IS NULL THEN ROLE_ID END
        );

CREATE INDEX IX_S2C_UR_ACTIVE
    ON S2C_USER_ROLE (USER_ID, USE_YN, VALID_FROM, VALID_TO);
-- UX_S2C_UR_OPEN_ACTIVE는 현재 V009에는 없지만,
-- Bootstrap의 중복 사용자-역할 생성과 동시 실행 경합을 DB에서도 차단하기 위해 새 이력에 포함할 것을 권장한다.

