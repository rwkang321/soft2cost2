    CONSTRAINT CK_S2C_UM_EXCEL CHECK (CAN_EXCEL IS NULL OR CAN_EXCEL IN ('Y','N')),
    CONSTRAINT CK_S2C_UM_APPROVE CHECK (CAN_APPROVE IS NULL OR CAN_APPROVE IN ('Y','N')),
    CONSTRAINT CK_S2C_UM_CLOSE CHECK (CAN_CLOSE IS NULL OR CAN_CLOSE IN ('Y','N')),
    CONSTRAINT CK_S2C_UM_COST CHECK (CAN_COST_VIEW IS NULL OR CAN_COST_VIEW IN ('Y','N')),
    CONSTRAINT CK_S2C_UM_SCOPE CHECK (DATA_SCOPE IS NULL OR DATA_SCOPE IN ('OWN','DEPT','SITE','COMPANY')),
    CONSTRAINT CK_S2C_UM_PERIOD CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CK_S2C_UM_USE CHECK (USE_YN IN ('Y','N'))

);

CREATE UNIQUE INDEX UX_UMA_OPEN_ACTIVE
    ON S2C_USER_MENU_AUTH (
                           CASE WHEN USE_YN = 'Y' AND VALID_TO IS NULL THEN USER_ID END,
                           CASE WHEN USE_YN = 'Y' AND VALID_TO IS NULL THEN MENU_ID END
        );

CREATE INDEX IX_S2C_UMA_ACTIVE
    ON S2C_USER_MENU_AUTH (USER_ID, USE_YN, VALID_FROM, VALID_TO, MENU_ID);

