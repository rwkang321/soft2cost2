CREATE TABLE S2C_USER
(
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    LOGIN_ID VARCHAR2(50) NOT NULL,
    USER_NAME VARCHAR2(100) NOT NULL,
    EMP_NO VARCHAR2(30),

    COMPANY_ID NUMBER NOT NULL,
    SITE_ID NUMBER,
    DEPT_ID NUMBER,

    EMAIL VARCHAR2(200),

    AUTH_TYPE VARCHAR2(20) DEFAULT 'LOCAL' NOT NULL,

    PASSWORD_HASH VARCHAR2(255),

    USER_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    FAILED_LOGIN_COUNT NUMBER DEFAULT 0 NOT NULL,
    LOCKED_UNTIL TIMESTAMP,

    PASSWORD_CHANGED_AT TIMESTAMP,
    MUST_CHANGE_PASSWORD_YN CHAR(1) DEFAULT 'Y' NOT NULL,
    LAST_LOGIN_AT TIMESTAMP,

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_USER PRIMARY KEY (USER_ID),
    -- CONSTRAINT UK_S2C_USER_LOGIN UNIQUE (LOGIN_ID),
    CONSTRAINT FK_S2C_USER_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES S2C_COMPANY(COMPANY_ID),
    CONSTRAINT FK_S2C_USER_SITE FOREIGN KEY (SITE_ID) REFERENCES S2C_SITE(SITE_ID),
    CONSTRAINT FK_S2C_USER_DEFT FOREIGN KEY (DEPT_ID) REFERENCES S2C_DEPT(DEPT_ID),
    CONSTRAINT FK_S2C_USER_COMPANY_SITE FOREIGN KEY (COMPANY_ID, SITE_ID) REFERENCES S2C_SITE (COMPANY_ID, SITE_ID),
    CONSTRAINT FK_S2C_USER_COMPANY_DEPT FOREIGN KEY (COMPANY_ID, DEPT_ID) REFERENCES S2C_DEPT (COMPANY_ID, DEPT_ID),
    CONSTRAINT CK_S2C_USER_AUTH CHECK (AUTH_TYPE IN ('LOCAL', 'SSO', 'LDAP')),
    CONSTRAINT CK_S2C_USER_STATUS CHECK (USER_STATUS IN ('ACTIVE','LOCKED','DORMANT','RETIRED')),
    CONSTRAINT CK_S2C_USER_MCP CHECK (MUST_CHANGE_PASSWORD_YN IN ('Y', 'N')),
    CONSTRAINT CK_S2C_USER_USE CHECK (USE_YN IN ('Y', 'N'))
);

-- UK_S2C_USER_LOGIN과 위 인덱스를 동시에 유지하면 대소문자 구분 유일 제약이 중복된다.
-- 새 설계에서는 UK_S2C_USER_LOGIN을 제거하고 UX_S2C_USER_LOGIN_UPPER 하나로 ADMIN, admin, Admin 중복을 막는다.
CREATE UNIQUE INDEX UX_S2C_USER_LOGIN_UPPER ON S2C_USER (UPPER(LOGIN_ID));

