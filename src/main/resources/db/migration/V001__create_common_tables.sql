CREATE TABLE S2C_MENU
(
    MENU_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    PARENT_MENU_ID NUMBER,

    MENU_CODE VARCHAR2(50) NOT NULL,
    MENU_NAME VARCHAR2(100) NOT NULL,

    MENU_LEVEL NUMBER DEFAULT 1 NOT NULL,

    MENU_TYPE VARCHAR2(20) DEFAULT 'SCREEN' NOT NULL,

    SCREEN_ID VARCHAR2(100),
    FORM_PATH VARCHAR2(300),

    ICON_NAME VARCHAR2(100),

    SORT_ORDER NUMBER DEFAULT 0,

    SENSITIVE_YN CHAR(1) DEFAULT 'N' NOT NULL,
    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_MENU PRIMARY KEY (MENU_ID),
    CONSTRAINT UK_S2C_MENU_CODE UNIQUE (MENU_CODE),
    CONSTRAINT FK_S2C_MENU_PARENT FOREIGN KEY (PARENT_MENU_ID) REFERENCES S2C_MENU(MENU_ID),
    CONSTRAINT CK_S2C_MENU_TYPE CHECK (MENU_TYPE IN ('GROUP','SCREEN','POPUP')),

    -- 계층과 화면 형식의 최소 계약 추가
    CONSTRAINT CK_S2C_MENU_LEVEL CHECK (MENU_LEVEL >= 1),
    CONSTRAINT CK_S2C_MENU_SHAPE CHECK (
        (MENU_TYPE = 'GROUP' AND SCREEN_ID IS NULL AND FORM_PATH IS NULL)
            OR (MENU_TYPE IN ('SCREEN','POPUP') AND SCREEN_ID IS NOT NULL AND FORM_PATH IS NOT NULL)
        ),
    -- DB Check만으로 자기 자신을 부모로 지정하거나 여러 단계 순환 참조를 완전히 막을 수는 없다.
    -- 해당 검사는 메뉴 수정 Service의 트랜잭션 안에서 수행해야 한다.

    CONSTRAINT CK_S2C_MENU_SENS CHECK (SENSITIVE_YN IN ('Y', 'N')),
    CONSTRAINT CK_S2C_MENU_USE CHECK (USE_YN IN ('Y', 'N'))
);

CREATE UNIQUE INDEX UX_S2C_MENU_CODE_UPPER ON S2C_MENU(UPPER(MENU_CODE));

