CREATE TABLE S2C_COMPANY
(
    COMPANY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_CODE VARCHAR2(20) NOT NULL,
    COMPANY_NAME VARCHAR2(100) NOT NULL,
    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
