    MENU_ID NUMBER NOT NULL,

    AUTH_LEVEL CHAR(1),

    CAN_EXCEL CHAR(1),
    CAN_APPROVE CHAR(1),
    CAN_CLOSE CHAR(1),
    CAN_COST_VIEW CHAR(1),

    DATA_SCOPE VARCHAR2(20),

