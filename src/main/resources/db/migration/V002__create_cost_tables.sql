/* ============================================================
   1. 프로젝트
   ============================================================ */

CREATE TABLE S2C_PROJECT
(
    PROJECT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    PROJECT_CODE VARCHAR2(30) NOT NULL,
    PROJECT_NAME VARCHAR2(200) NOT NULL,

    COMPANY_ID NUMBER NOT NULL,

    CUSTOMER_CODE VARCHAR2(30),
    CUSTOMER_NAME VARCHAR2(200),

    CONTRACT_AMOUNT NUMBER(20, 2),
    CURRENCY_CODE VARCHAR2(10),

    START_DATE DATE,
    END_DATE DATE,

    PROJECT_STATUS VARCHAR2(20) DEFAULT 'PLAN',

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_PROJECT PRIMARY KEY (PROJECT_ID),
    CONSTRAINT UK_S2C_PROJECT_CODE UNIQUE (PROJECT_CODE),
    CONSTRAINT FK_S2C_PROJECT_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES S2C_COMPANY(COMPANY_ID)
);

/* ============================================================
   2. 호선
   ============================================================ */

CREATE TABLE S2C_HULL
(
    HULL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    PROJECT_ID NUMBER NOT NULL,

    HULL_NO VARCHAR2(30) NOT NULL,

    VESSEL_TYPE VARCHAR2(100),
    VESSEL_NAME VARCHAR2(200),

    START_DATE DATE,
    DELIVERY_DATE DATE,

    HULL_STATUS VARCHAR2(20) DEFAULT 'PLAN',

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_HULL PRIMARY KEY (HULL_ID),
    CONSTRAINT UK_S2C_HULL_NO UNIQUE (HULL_NO),
    CONSTRAINT FK_S2C_HULL_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES S2C_PROJECT(PROJECT_ID)
);

/* ============================================================
   3. WBS-WORK BREAKDOWN STRUCTURE : 반드시 "TREE" 구조로 만들어야 한다. : 어떤 일을 하는가?
   ============================================================ */

CREATE TABLE S2C_WBS
(
    WBS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    HULL_ID NUMBER NOT NULL,

    PARENT_WBS_ID NUMBER,

    WBS_CODE VARCHAR2(50) NOT NULL,
    WBS_NAME VARCHAR2(200) NOT NULL,

    WBS_LEVEL NUMBER DEFAULT 1 NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0,

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_WBS PRIMARY KEY (WBS_ID),
    CONSTRAINT UK_S2C_WBS_CODE UNIQUE (HULL_ID, WBS_CODE),
    CONSTRAINT UK_S2C_WBS_HULL_ID UNIQUE (HULL_ID, WBS_ID),
    CONSTRAINT FK_S2C_WBS_HULL FOREIGN KEY (HULL_ID) REFERENCES S2C_HULL(HULL_ID),
    --CONSTRAINT FK_S2C_WBS_PARENT FOREIGN KEY (PARENT_WBS_ID) REFERENCES S2C_WBS(WBS_ID)
    CONSTRAINT FK_S2C_WBS_PARENT_HULL FOREIGN KEY (HULL_ID, PARENT_WBS_ID) REFERENCES S2C_WBS(HULL_ID, WBS_ID)
);

/* ============================================================
   4. CBS-COST BREAKDOWN STRUCTURE : 반드시 "TREE" 구조로 만들어야 한다. : 어떤 종류의 비용이 발생했는가?
   ============================================================ */

CREATE TABLE S2C_CBS
(
    CBS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    PARENT_CBS_ID NUMBER,

    CBS_CODE VARCHAR2(50) NOT NULL,
    CBS_NAME VARCHAR2(200) NOT NULL,

    COST_TYPE VARCHAR2(30),

    CBS_LEVEL NUMBER DEFAULT 1 NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0,

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_CBS PRIMARY KEY (CBS_ID),
    CONSTRAINT UK_S2C_CBS_CODE UNIQUE (CBS_CODE),
    CONSTRAINT FK_S2C_CBS_PARENT FOREIGN KEY (PARENT_CBS_ID) REFERENCES S2C_CBS(CBS_ID)
);

/* ============================================================
   5. WORK PACKAGE : WBS를 실제 관리 가능한 작업 단위로 쪼갠 것
   ============================================================ */

CREATE TABLE S2C_WORK_PACKAGE
(
    WORK_PACKAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    HULL_ID NUMBER NOT NULL,
    WBS_ID NUMBER NOT NULL,

    WP_CODE VARCHAR2(50) NOT NULL,
    WP_NAME VARCHAR2(200) NOT NULL,

    RESPONSIBLE_DEPT_ID NUMBER,

    START_DATE DATE,
    END_DATE DATE,

    STATUS_CODE VARCHAR2(20) DEFAULT 'PLAN',

    USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY VARCHAR2(50),

    CONSTRAINT PK_S2C_WORK_PACKAGE PRIMARY KEY (WORK_PACKAGE_ID),
    CONSTRAINT UK_S2C_WP_CODE UNIQUE (WP_CODE),
    CONSTRAINT FK_S2C_WP_HULL FOREIGN KEY (HULL_ID) REFERENCES S2C_HULL(HULL_ID),
    CONSTRAINT FK_S2C_WP_HULL_WBS FOREIGN KEY (HULL_ID, WBS_ID) REFERENCES S2C_WBS (HULL_ID, WBS_ID),
    CONSTRAINT FK_S2C_WP_WBS FOREIGN KEY (WBS_ID) REFERENCES S2C_WBS(WBS_ID),
    CONSTRAINT FK_S2C_WP_DEPT FOREIGN KEY (RESPONSIBLE_DEPT_ID) REFERENCES S2C_DEPT(DEPT_ID)
);

